    # 反过来乘一次：B @ A —— 结果完全不同！
    _D = B @ A
    # _D[0, 0] = 5×1 + 6×3 = 23；_D[0, 1] = 5×2 + 6×4 = 34
    # _D[1, 0] = 7×1 + 8×3 = 31；_D[1, 1] = 7×2 + 8×4 = 46

